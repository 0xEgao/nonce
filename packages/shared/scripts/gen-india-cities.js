// Regenerates src/location-data/india-cities.ts from a GeoNames cities dump.
//
//   curl -O https://download.geonames.org/export/dump/cities5000.zip && unzip cities5000.zip
//   node packages/shared/scripts/gen-india-cities.js cities5000.txt packages/shared/src/location-data
const fs = require('fs');
const path = require('path');
const [citiesPath, outDir] = process.argv.slice(2);

// GeoNames admin1 code -> ISO 3166-2:IN code (current codes, post-2023).
const ADMIN1 = {
  '01': 'AN', '02': 'AP', '30': 'AR', '03': 'AS', '34': 'BR', '05': 'CH', '37': 'CG', '52': 'DH', '07': 'DL',
  '33': 'GA', '09': 'GJ', '10': 'HR', '11': 'HP', '12': 'JK', '38': 'JH', '19': 'KA', '13': 'KL', '41': 'LA',
  '14': 'LD', '35': 'MP', '16': 'MH', '17': 'MN', '18': 'ML', '31': 'MZ', '20': 'NL', '21': 'OD', '22': 'PY',
  '23': 'PB', '24': 'RJ', '29': 'SK', '25': 'TN', '40': 'TS', '26': 'TR', '36': 'UP', '39': 'UK', '28': 'WB',
};
const byState = {};
for (const line of fs.readFileSync(citiesPath, 'utf8').split('\n')) {
  const f = line.split('\t');
  if (f[8] !== 'IN') continue;
  const pop = Number(f[14]);
  const fc = f[7];
  if (!(pop >= 15000 || fc === 'PPLA' || fc === 'PPLA2' || fc === 'PPLC')) continue;
  const state = ADMIN1[f[10]];
  if (!state) { console.error('skip (no state):', f[2], f[10]); continue; }
  (byState[state] ??= []).push({ name: f[2].trim(), pop });
}
const out = {};
let total = 0;
for (const code of Object.values(ADMIN1).sort()) {
  const seen = new Set();
  const list = (byState[code] ?? []).sort((a, b) => b.pop - a.pop).filter((c) => {
    const k = c.name.toLowerCase();
    if (!c.name || seen.has(k)) return false;
    seen.add(k);
    return true;
  }).map((c) => c.name);
  out[code] = list;
  total += list.length;
}
const indiaCitiesTs = `// Generated by packages/shared/scripts/gen-india-cities.js; edit the generator, not this file.
//
// Cities offered in the India city dropdown, keyed by ISO 3166-2:IN state code
// and ordered by population (largest first). Places with 15,000+ people plus
// every district and state capital. The dropdown also accepts a typed city, so
// a missing town is never a dead end.
//
// Source: GeoNames (https://www.geonames.org), cities5000 dump, licensed under
// CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Names are the
// GeoNames ASCII names.

// prettier-ignore
export const INDIA_CITIES_BY_STATE: Readonly<Record<string, readonly string[]>> = {
${Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')}
};
`;
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'india-cities.ts'), indiaCitiesTs);
console.log('cities', total, Object.entries(out).map(([k, v]) => k + ':' + v.length).join(' '));
